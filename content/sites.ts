/** Largest face in the estate, by area. Used on the network page. */
export const largestFace = sites.reduce((best, site) =>
  site.widthFt * site.heightFt > best.widthFt * best.heightFt ? site : best,
);

export function getSite(id: string): MediaSite | undefined {
  return sites.find((site) => site.id === id);
}

export function sitesInCity(city: City): MediaSite[] {
  return sites.filter((site) => site.city === city);
}

/** Area → site count, largest first. Used on the network page. */
export function areaBreakdown(): { area: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const site of sites) counts.set(site.area, (counts.get(site.area) ?? 0) + 1);
  return [...counts.entries()]
    .map(([area, count]) => ({ area, count }))
    .sort((a, b) => b.count - a.count);
}
